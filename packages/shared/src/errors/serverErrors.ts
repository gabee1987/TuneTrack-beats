export type ServerErrorCode = (typeof SERVER_ERROR_CODES)[number];

const serverErrorCodes: ReadonlySet<string> = new Set(SERVER_ERROR_CODES);

export function isServerErrorCode(code: string): code is ServerErrorCode {
  return serverErrorCodes.has(code);
}

/** An expected refusal; its code reaches the client. Anything else is reported as a fallback. */
export class DomainError extends Error {
  public constructor(public readonly code: ServerErrorCode) {
    super(code);
    this.name = "DomainError";
  }
}
